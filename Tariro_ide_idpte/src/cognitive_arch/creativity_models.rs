// Tariro_ide_idpte/src/cognitive_arch/creativity_models.rs

//! Defines data models for Tariro's Creativity & Innovation Generation module,
//! including creative prompts, novel solutions, and patent claims.

use serde::{Serialize, Deserialize};
use chrono::{Utc, DateTime};
use std::collections::HashMap;

use crate::cognitive_arch::learning_models::VerificationStatus; // For verification statuses

/// Represents an input prompt for generating creative output.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CreativePrompt {
    pub id: String,
    pub description: String,
    pub domain: String, // e.g., "software_development", "music_composition", "scientific_theory"
    pub constraints: Vec<String>, // e.g., "must be Rust code", "must be lyrical", "must explain X"
    pub source: String, // e.g., "HumanUser", "InternalGoal", "CuriosityModule"
    pub timestamp: DateTime<Utc>,
}

/// Represents a novel solution or creative output generated by Tariro.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct NovelSolution {
    pub id: String,
    pub prompt_id: String,
    pub solution_summary: String,
    pub content_type: String, // e.g., "rust_code", "musical_score", "scientific_hypothesis"
    pub originality_score: f64, // 0.0 (unoriginal) to 1.0 (highly novel)
    pub utility_score: f64, // 0.0 (useless) to 1.0 (highly useful)
    pub generation_process_summary: String, // How it was created
    pub verification_status: SolutionVerificationStatus, // New: Ethical/Security review status
    pub created_at: DateTime<Utc>,
    pub owner_agent_id: String, // New: ID of the agent who 'owns' the creation (Tariro or human)
}

/// Represents a patent claim or similar intellectual property record for a novel solution.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PatentClaim {
    pub id: String,
    pub solution_id: String,
    pub claim_text: String,
    pub claimant_id: String, // e.g., "Tariro", "Samuel Mukandara"
    pub filing_status: String, // e.g., "draft", "pending", "granted", "rejected"
    pub blockchain_record_hash: Option<String>, // New: Tamper-proof record hash
    pub filed_at: DateTime<Utc>,
    pub integrity_verified: VerificationStatus, // New: Integrity of the claim itself
}

/// A report summarizing the ethical compliance of creative output.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct EthicalCreativeOutputReport {
    pub id: String,
    pub solution_id: String,
    pub ethical_compliance_status: VerificationStatus, // From ALEC-A
    pub identified_biases: Vec<String>,
    pub potential_harm_summary: String,
    pub recommendations_for_mitigation: Vec<String>,
    pub generated_at: DateTime<Utc>,
}

/// Comprehensive verification status for a creative solution.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SolutionVerificationStatus {
    pub ethical_compliance_status: VerificationStatus, // From ALEC-A
    pub security_compliance_status: VerificationStatus, // From QR-CTFO
    pub originality_verification_status: VerificationStatus, // Checked against existing works
    pub overall_status: VerificationStatus,
    pub last_verified: DateTime<Utc>,
    pub verification_log_id: String,
}
