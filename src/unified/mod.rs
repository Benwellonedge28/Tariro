/// Unified TUMC-AGI configuration
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct UnifiedConfig {
    /// Enable cognitive compiler
    pub enable_cognitive_compiler: bool,

    /// Enable meta-learning
    pub enable_meta_learning: bool,

    /// Enable AGI reasoning
    pub enable_agi_reasoning: bool,

    /// Enable self-modification
    pub enable_self_modification: bool,

    /// Default optimization level
    pub default_optimization: String,

    /// Target platform
    pub target_platform: String,

    /// Maximum reasoning depth
    pub max_reasoning_depth: usize,

    /// Memory size for unified memory (MB)
    pub memory_size_mb: usize,
}

impl Default for UnifiedConfig {
    fn default() -> Self {
        Self {
            enable_cognitive_compiler: true,
            enable_meta_learning: true,
            enable_agi_reasoning: true,
            enable_self_modification: true,
            default_optimization: "O3".to_string(),
            target_platform: "wasm".to_string(),
            max_reasoning_depth: 10,
            memory_size_mb: 1024,
        }
    }
}

/// System status
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SystemStatus {
    pub version: String,
    pub uptime_mts: u128,
    pub components: HashMap<String, ComponentStatus>,
    pub metrics: SystemMetrics,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ComponentStatus {
    pub name: String,
    pub initialized: bool,
    pub healthy: bool,
    pub error: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SystemMetrics {
    pub compilations_completed: u64,
    pub insights_generated: u64,
    pub optimizations_applied: u64,
    pub memory_usage_mb: usize,
    pub active_agents: usize,
}

/// Intent processing result
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct IntentResult {
    pub success: bool,
    pub output: String,
    pub insights: Vec<AgiInsight>,
    pub metrics: ProcessingMetrics,
    pub errors: Vec<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ProcessingMetrics {
    pub compilation_time_ms: u64,
    pub reasoning_steps: usize,
    pub optimizations_applied: usize,
    pub confidence: f64,
}

/// Intent type - represents the type of AGI intent
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub enum IntentType {
    /// Compile source code to target
    Compile,
    /// Analyze code structure
    Analyze,
    /// Optimize code performance
    Optimize,
    /// Reason about a problem
    Reason,
    /// Learn from experience
    Learn,
    /// Create new content
    Create,
    /// Search for information
    Search,
    /// Plan actions
    Plan,
    /// Execute a task
    Execute,
    /// Understand context
    Understand,
    /// Generate text
    Generate,
    /// Transform data
    Transform,
}

/// Intent - Represents an intent to be processed by the AGI system
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Intent {
    /// Type of intent
    pub intent_type: IntentType,
    /// Description of the intent
    pub description: String,
    /// Additional context for processing
    pub context: HashMap<String, String>,
}

impl Intent {
    /// Create a new intent
    pub fn new(intent_type: IntentType, description: String) -> Self {
        Self {
            intent_type,
            description,
            context: HashMap::new(),
        }
    }

    /// Create a new intent with context
    pub fn with_context(intent_type: IntentType, description: String, context: HashMap<String, String>) -> Self {
        Self {
            intent_type,
            description,
            context,
        }
    }
}

impl Default for IntentType {
    fn default() -> Self {
        IntentType::Understand
    }
}

/// Unified result from processing an intent
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct UnifiedResult {
    /// Whether the operation succeeded
    pub success: bool,
    /// Output of the operation
    pub output: String,
    /// Insights generated during processing
    pub insights: Vec<AgiInsight>,
    /// Processing metrics
    pub metrics: ProcessingMetrics,
    /// Any errors that occurred
    pub errors: Vec<String>,
}

impl UnifiedResult {
    /// Create a successful result
    pub fn success(output: String, metrics: ProcessingMetrics) -> Self {
        Self {
            success: true,
            output,
            insights: Vec::new(),
            metrics,
            errors: Vec::new(),
        }
    }

    /// Create a failed result
    pub fn failure(error: String) -> Self {
        Self {
            success: false,
            output: String::new(),
            insights: Vec::new(),
            metrics: ProcessingMetrics {
                compilation_time_ms: 0,
                reasoning_steps: 0,
                optimizations_applied: 0,
                confidence: 0.0,
            },
            errors: vec![error],
        }
    }
}

/// Unified status information
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct UnifiedStatus {
    pub version: String,
    pub uptime_mts: u128,
    pub components: HashMap<String, ComponentStatus>,
    pub metrics: SystemMetrics,
    pub active_engines: usize,
    pub total_intents_processed: u64,
}

impl UnifiedStatus {
    /// Create a default status
    pub fn default() -> Self {
        Self {
            version: env!("CARGO_PKG_VERSION").to_string(),
            uptime_mts: 0,
            components: HashMap::new(),
            metrics: SystemMetrics {
                compilations_completed: 0,
                insights_generated: 0,
                optimizations_applied: 0,
                memory_usage_mb: 0,
                active_agents: 0,
            },
            active_engines: 0,
            total_intents_processed: 0,
        }
    }
}

impl Default for UnifiedStatus {
    fn default() -> Self {
        Self::default()
    }
}

/// Create a new unified TUMC-AGI system
pub fn create_tariro_unified(config: UnifiedConfig) -> TariroUnifiedOrchestrator {
    TariroUnifiedOrchestrator::new(config)
}
