//! # Attribution Manager
//!
//! Manages attribution and provenance for creative works.

use crate::authorship::CreativeConcept;
use serde::{Deserialize, Serialize};

/// Provenance record for a creative work
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ProvenanceRecord {
    /// Unique identifier
    pub id: String,
    /// Author information
    pub author: AuthorInfo,
    /// Creation metadata
    pub created_at: chrono::DateTime<chrono::Utc>,
    /// Generation details
    pub generation: GenerationInfo,
    /// Modification history
    pub modifications: Vec<ModificationRecord>,
    /// Licensing information
    pub license: LicenseInfo,
    /// Verification signature
    pub signature: Option<String>,
}

/// Author information
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AuthorInfo {
    /// Author type
    pub author_type: AuthorType,
    /// Name or identifier
    pub name: String,
    /// Attribution requirements
    pub attribution_required: bool,
    /// Contact or reference
    pub reference: Option<String>,
}

/// Type of author
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub enum AuthorType {
    /// Human author
    Human,
    /// AGI author
    AGI,
    /// Human-AGI collaboration
    Collaborative,
}

/// Generation information
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct GenerationInfo {
    /// Engine used
    pub engine: String,
    /// Version
    pub version: String,
    /// Iterations
    pub iterations: u32,
    /// Quality score
    pub quality_score: f64,
    /// Parameters used
    pub parameters: serde_json::Map<String, serde_json::Value>,
}

/// Modification record
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ModificationRecord {
    pub timestamp: chrono::DateTime<chrono::Utc>,
    pub modifier: String,
    pub description: String,
    pub version: u32,
}

/// License information
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct LicenseInfo {
    pub name: String,
    pub url: Option<String>,
    pub attribution_text: Option<String>,
    pub commercial_use: bool,
    pub modifications_allowed: bool,
}

impl ProvenanceRecord {
    /// Create a new provenance record
    pub fn new(concept: &CreativeConcept, iterations: u32) -> Self {
        Self {
            id: uuid::Uuid::new_v4().to_string(),
            author: AuthorInfo {
                author_type: AuthorType::AGI,
                name: "Tariro AGI".to_string(),
                attribution_required: true,
                reference: Some("https://tariro.dev".to_string()),
            },
            created_at: chrono::Utc::now(),
            generation: GenerationInfo {
                engine: "Tariro AGI Authorship Engine".to_string(),
                version: env!("CARGO_PKG_VERSION").to_string(),
                iterations,
                quality_score: 0.0,
                parameters: serde_json::Map::new(),
            },
            modifications: Vec::new(),
            license: LicenseInfo {
                name: "MIT".to_string(),
                url: Some("https://opensource.org/licenses/MIT".to_string()),
                attribution_text: Some("Generated by Tariro AGI".to_string()),
                commercial_use: true,
                modifications_allowed: true,
            },
            signature: None,
        }
    }

    /// Add a modification record
    pub fn add_modification(&mut self, modifier: &str, description: &str) {
        let version = self.modifications.len() as u32 + 1;
        self.modifications.push(ModificationRecord {
            timestamp: chrono::Utc::now(),
            modifier: modifier.to_string(),
            description: description.to_string(),
            version,
        });
    }

    /// Set quality score
    pub fn set_quality(&mut self, score: f64) {
        self.generation.quality_score = score;
    }
}

impl Default for ProvenanceRecord {
    fn default() -> Self {
        let mut record = Self::new(
            &CreativeConcept::new("Default".to_string(), "Default".to_string()),
            0,
        );
        record
    }
}

/// Attribution manager
pub struct AttributionManager;

impl AttributionManager {
    /// Create a new attribution manager
    pub fn new() -> Self {
        Self
    }

    /// Create provenance for a work
    pub fn create_provenance(&self, concept: &CreativeConcept, iterations: u32) -> ProvenanceRecord {
        ProvenanceRecord::new(concept, iterations)
    }

    /// Generate attribution text
    pub fn generate_attribution(&self, provenance: &ProvenanceRecord) -> String {
        let mut attribution = String::new();

        attribution.push_str("## Attribution\n\n");
        attribution.push_str(&format!(
            "This work was created by {}.\n\n",
            provenance.author.name
        ));

        if let Some(ref url) = provenance.author.reference {
            attribution.push_str(&format!("Reference: {}\n\n", url));
        }

        attribution.push_str(&format!(
            "Generated using {} v{}\n",
            provenance.generation.engine,
            provenance.generation.version
        ));

        if let Some(ref license) = provenance.license.attribution_text {
            attribution.push_str(&format!("License: {} ({})\n", provenance.license.name, license));
        }

        attribution
    }

    /// Verify provenance
    pub fn verify(&self, provenance: &ProvenanceRecord) -> bool {
        // In production, would verify cryptographic signature
        !provenance.id.is_empty() && !provenance.author.name.is_empty()
    }
}

impl Default for AttributionManager {
    fn default() -> Self {
        Self::new()
    }
}
